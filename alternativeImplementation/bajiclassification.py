"""## CNN Train

"""

from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Conv2D, MaxPooling2D, Flatten, Dense, Dropout
from tensorflow.keras.optimizers import Adam
from sklearn.model_selection import train_test_split
from tensorflow.keras.callbacks import EarlyStopping

"""Train/test split"""

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.25,       # Here 25% of the data is used
    random_state=42,      # Changing this parameter will generate different sets of train/test
    shuffle=True,
    stratify=y,
)

print(f"Train: {X_train.shape} | Val: {X_test.shape}")

input_shape = X_train.shape[1:]

model = Sequential([
      # Conv2D scans the mspec "image" for local patterns (voice texture, formants)
      # 16 filters = 16 different patterns to detect
      # kernel (3,3) = each filter looks at a 3x3 patch at a time
      Conv2D(16, kernel_size=(3,3), activation='relu', input_shape=input_shape),

      # Downsamples by taking the max value in each 2x2 block
      # reduces computation and makes detected patterns more robust to small shifts
      MaxPooling2D(pool_size=(2,2)),

      # Converts the 2D feature map into a 1D vector so Dense layers can process it
      Flatten(),

      # Learns combinations of the CNN features that distinguish Baji from Lowji
      Dense(16, activation='relu'),

      # Single output neuron: 0 = Baji, 1 = Lowji
      # sigmoid squashes output to 0–1 so it can be treated as a probability
      Dense(1, activation='sigmoid')
  ])

# Adam handles learning rate automatically, good default optimizer
# binary_crossentropy is the standard loss for two-class problems
model.compile(optimizer=Adam(), loss='binary_crossentropy', metrics=['accuracy'])
model.summary()

# stops training when val_loss stops improving, restores best weights
early_stop = EarlyStopping(
      monitor='val_loss',
      patience=5,        # stops after 5 epochs of no improvement
      restore_best_weights=True
  )

history = model.fit(
      X_train, y_train,
      validation_data=(X_test, y_test),  # model never trains on val, only evaluates
      epochs=50,                        # same as WakeWord notebook
      batch_size = 4,                     # same as WakeWord notebook
      callbacks=[early_stop]
)

