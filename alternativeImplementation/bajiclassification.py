"""## Audio Windowing"""

import librosa
import numpy as np

BAJI_PATH = "/content/drive/MyDrive/Voice Samples/Train/Baji Talking.wav"
LOWJI_PATH = "/content/drive/MyDrive/Voice Samples/Train/Lowji Talking.wav"

SR = 16000
WINDOW_SEC = 1.0
N_MSPEC = 20
N_WINDOWS = 2000
TOP_DB = 30  # increase if too much silence slips through, decrease if too much speech is cut

def sample_windows(audio_path, label, window_sec=WINDOW_SEC, sr=SR, n_mspec=N_MSPEC, n_windows=N_WINDOWS):
      print(f"Loading {audio_path}...")
      audio, _ = librosa.load(audio_path, sr=sr, mono=True)
      window_len = int(window_sec * sr)

      # Get non-silent intervals and concatenate them
      intervals = librosa.effects.split(audio, top_db=TOP_DB)
      speech_audio = np.concatenate([audio[start:end] for start, end in intervals])
      print(f"  Speech after silence removal: {len(speech_audio)/sr:.1f}s of {len(audio)/sr:.1f}s")
      #Randomly sample 2000 windows
      X, y = [], []
      for _ in range(n_windows):
          start = np.random.randint(0, len(speech_audio) - window_len)
          segment = speech_audio[start : start + window_len]
          mspec = librosa.feature.melspectrogram(y=segment, sr=sr)
          X.append(mspec[..., np.newaxis])
          y.append(label)
      print(f"  Done. Shape: {np.array(X).shape}")
      return np.array(X), np.array(y)
#extract mel-spectrogram from each chunk and converts it into 2D feature matrix
X_baji,  y_baji  = sample_windows(BAJI_PATH,  label=0)
X_lowji, y_lowji = sample_windows(LOWJI_PATH, label=1)

X = np.concatenate([X_baji,  X_lowji])
y = np.concatenate([y_baji, y_lowji])

print(f"Total dataset: {X.shape}, labels: {y.shape}")

