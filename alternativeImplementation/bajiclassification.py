"""### Generating accuracy statistic"""

correct_predictions = 0
total_predictions_considered = 0

with open(LABELS_TEST_PATH, 'r') as f:
    for line in f:
        parts = line.strip().split('\t')
        if len(parts) != 3:
            print(f"Warning: Skipping malformed line in Labels.txt: {line.strip()}")
            continue

        start_seg = float(parts[0])
        end_seg = float(parts[1])
        code = int(parts[2])

        ground_truth_label = None
        is_dont_care = False

        if code == 111: # Baji
            ground_truth_label = 0
        elif code == 211: # Lowji
            ground_truth_label = 1
        elif code == 133: # Baji breathing, don't really care if it gets it right
            ground_truth_label = 0
            is_dont_care = True
        elif code == 233: # Lowji breathing, same as above
            ground_truth_label = 1
            is_dont_care = True
        else:
            print(f"Warning: Unknown code {code} in Labels.txt. Skipping segment {start_seg}-{end_seg}.")
            continue

        # Iterate through all CNN predictions and their timestamps
        for i in range(len(timestamps)):
            cnn_timestamp = timestamps[i]
            cnn_predicted_label = labels[i]

            # Consider predictions whose start timestamp falls within the ground truth segment
            # if a prediction falls outside of a truth segment, truth is silence, so answer is irrelevent
            if start_seg <= cnn_timestamp < end_seg:
                if is_dont_care:
                    # If it's a 'don't care' code and CNN predicts correctly, count it.
                    # If CNN predicts incorrectly, it's ignored (neither correct nor incorrect).
                    if cnn_predicted_label == ground_truth_label:
                        correct_predictions += 1
                        total_predictions_considered += 1
                else: # Not a 'don't care' code (111 or 211)
                    total_predictions_considered += 1
                    if cnn_predicted_label == ground_truth_label:
                        correct_predictions += 1

# Calculate accuracy
if total_predictions_considered > 0:
    accuracy = (correct_predictions / total_predictions_considered) * 100
    print(f"\nAccuracy: {accuracy:.2f}% ({correct_predictions} correct out of {total_predictions_considered} considered predictions)")
else:
    print("\nNo relevant predictions found within the labeled segments in Labels.txt to calculate accuracy.")